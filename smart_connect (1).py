def normalize_diagnosis(text):
    if pd.isna(text):
        return "Unknown"

    text = text.lower()

    if any(x in text for x in ["kidney", "aki", "urea", "creatinine"]):
        return "Kidney Disease"
    elif any(x in text for x in ["liver", "hepatic"]):
        return "Liver Disease"
    elif any(x in text for x in ["stroke", "faint", "neuro"]):
        return "Neurological"
    elif any(x in text for x in ["heart", "cardiac"]):
        return "Cardiovascular"
    elif any(x in text for x in ["diabetes", "glucose"]):
        return "Diabetes"
    else:
        return "Other"

