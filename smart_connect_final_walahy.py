def normalize_diagnosis(text):
    """
    Merge diagnoses into 10-11 clear categories
    """
    if pd.isna(text):
        return "Other"

    text = str(text).lower()

    # 1. KIDNEY (Merge ALL kidney issues into ONE category)
    if any(word in text for word in ['kidney', 'renal', 'aki', 'ckd', 'nephritis', 'acute kidney', 'kidney failure']):
        return "Kidney_Disease"

    # 2. PNEUMONIA & LUNG INFECTIONS
    elif any(word in text for word in ['pneumonia', 'lung infection', 'chest infection', 'respiratory infection']):
        return "Pneumonia"

    # 3. SEPSIS & SEVERE INFECTIONS
    elif any(word in text for word in ['sepsis', 'septic']):
        return "Sepsis"

    # 4. UTI
    elif any(word in text for word in ['uti', 'urinary tract']):
        return "UTI"

    # 5. STROKE
    elif any(word in text for word in ['stroke', 'cva', 'cerebrovascular']):
        return "Stroke"

    # 6. HEART DISEASE (Merge all cardiac issues)
    elif any(word in text for word in ['heart', 'cardiac', 'mi ', 'infarct', 'coronary']):
        return "Heart_Disease"

    # 7. DIABETES (Merge all diabetic emergencies)
    elif any(word in text for word in ['diabetes', 'diabetic', 'dka', 'ketoacid', 'hyperglycemia']):
        return "Diabetes_Emergency"

    # 8. ANEMIA
    elif any(word in text for word in ['anemia', 'anaemia']):
        return "Anemia"

    # 9. RESPIRATORY (Non-infection, merge COPD, asthma, etc.)
    elif any(word in text for word in ['copd', 'asthma', 'pulmonary edema', 'respiratory failure', 'bronchitis']):
        return "Respiratory_Disease"

    # 10. GASTROINTESTINAL (Merge all GI issues)
    elif any(word in text for word in ['gastro', 'gi ', 'intestin', 'stomach', 'abdomen', 'liver', 'hepatic', 'cirrhosis']):
        return "Gastrointestinal"

    # 11. Everything else
    else:
        return "Other"

