def clean_diagnosis(text):
    """Remove Arabic characters, special symbols, extra spaces"""
    if pd.isna(text):
        return np.nan

    # Convert to string
    text = str(text)

    # Remove Arabic/non-ASCII characters
    text = re.sub(r'[^\x00-\x7F]+', '', text)

    # Remove extra punctuation except comma and hyphen
    text = re.sub(r'[^\w\s,\-]', '', text)

    # Remove extra spaces
    text = ' '.join(text.split())

    # Remove leading/trailing whitespace
    text = text.strip()

    # If empty after cleaning, return NaN
    if not text:
        return np.nan

    return text.lower()

